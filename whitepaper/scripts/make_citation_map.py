def harvest(path: Path) -> list[tuple[str, str]]:
    """(section title, citation key) for every \\citep in one document."""
    sec, out = "(front matter)", []
    for ln in path.read_text().split("\n"):
        m = re.match(r"\\(sub)?section\*?\{(.+?)\}\s*$", ln)
        if m:
            sec = re.sub(r"\\[a-zA-Z]+|\{|\}|\$", "", m.group(2)).strip()
        for c in re.finditer(r"\\citep\{([^}]*)\}", ln):
            for key in c.group(1).split(","):
                out.append((sec, key.strip()))
    return out


def uniq(xs):
    seen, out = set(), []
    for x in xs:
        if x not in seen:
            seen.add(x)
            out.append(x)
    return out


def main() -> None:
    rows: dict[str, dict[str, list[str]]] = {}
    for name in ("main", "brief"):
        for sec, key in harvest(ROOT / f"{name}.tex"):
            rows.setdefault(key, {"main": [], "brief": []})[name].append(sec)

    bib = (ROOT / "references.bib").read_text()
    verify = set(re.findall(r"^% VERIFY (\S+):", bib, re.M))
    noted = set(re.findall(r"^% NOTE (\S+):", bib, re.M))
    order = re.findall(r"^@\w+\{([^,]+),", bib, re.M)

    out = [PREAMBLE, "| Key | Flag | In `main.pdf` | In `brief.pdf` |", "|---|:---:|---|---|"]
    for key in order:
        r = rows.get(key, {"main": [], "brief": []})
        mark = "**yes**" if key in verify else ("note" if key in noted else "--")
        out.append(f"| `{key}` | {mark} | {'; '.join(uniq(r['main'])) or '*not cited*'} "
                   f"| {'; '.join(uniq(r['brief'])) or '*not cited*'} |")

    n_main = sum(len(v["main"]) for v in rows.values())
    n_brief = sum(len(v["brief"]) for v in rows.values())
    out.append(f"\nTotals: {n_main} citation calls in `main.tex`, {n_brief} in `brief.tex`, "
               f"over {len(order)} entries, {len(verify)} needing verification and "
               f"{len(noted)} carrying a selection note.")
    out.append(CHECKLIST)

    path = ROOT / "data" / "citation-map.md"
    path.write_text("\n".join(out) + "\n")
    print(f"wrote data/citation-map.md  ({n_main} main + {n_brief} brief calls, "
          f"{len(verify)} verify, {len(noted)} note)")


if __name__ == "__main__":
    main()
